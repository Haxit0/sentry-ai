"""Generate the Zetaris development dataset from the validated fixture.

The fixture stays the single source of truth. Its records are split across two
independent sources so Zetaris federates them:

- PostgreSQL (`sentry_hackathon_dev.public.customer_orders`): customer orders.
- Zetaris filestore CSV (`SENTRY_SUPPLIER_PORTAL.suppliers` / `.inventory`):
  supplier offers and on-hand stock.

Usage, from `backend`:  python -m scripts.zetaris_dataset [--check]
"""

import csv
import io
import sys
from pathlib import Path

from app.data.repository import FixtureRepository
from app.schemas import DemoData

OUT_DIR = Path(__file__).resolve().parent.parent / "zetaris_dataset"

SUPPLIER_COLUMNS = (
    "supplier_id", "name", "sku", "restock_date", "replenishment_quantity",
    "expedite_days_saved", "expedite_capacity_units", "expedite_fixed_fee_gbp", "expedite_per_unit_fee_gbp",
    "alternative_supplier_name", "alternative_lead_time_days", "alternative_capacity_units",
    "alternative_fixed_fee_gbp", "alternative_unit_premium_gbp",
)
INVENTORY_COLUMNS = ("sku", "on_hand_units")


def _csv(header: tuple[str, ...], rows: list[tuple[object, ...]]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return buffer.getvalue()


def _sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render(data: DemoData) -> dict[str, str]:
    suppliers = _csv(SUPPLIER_COLUMNS, [(
        s.supplier_id, s.name, s.sku, s.restock_date.isoformat(), s.replenishment_quantity,
        s.expedite.days_saved, s.expedite.capacity_units,
        f"{s.expedite.fixed_fee_gbp:.2f}", f"{s.expedite.per_unit_fee_gbp:.2f}",
        s.alternative.supplier_name, s.alternative.lead_time_days, s.alternative.capacity_units,
        f"{s.alternative.fixed_fee_gbp:.2f}", f"{s.alternative.unit_premium_gbp:.2f}",
    ) for s in data.suppliers])
    inventory = _csv(INVENTORY_COLUMNS, [(item.sku, item.on_hand_units) for item in data.inventory])
    values = ",\n".join(
        f"  ({_sql_text(o.order_id)}, {_sql_text(o.customer_name)}, {_sql_text(o.supplier_id)}, "
        f"{_sql_text(o.sku)}, {o.quantity}, DATE '{o.promised_date.isoformat()}', {o.penalty_per_day_gbp:.2f})"
        for o in data.orders
    )
    orders = (
        "-- Generated by backend/scripts/zetaris_dataset.py from backend/app/data/demo_data.json.\n"
        "-- Synthetic development records only. Applied inside database sentry_hackathon_dev.\n"
        "DROP TABLE IF EXISTS public.customer_orders;\n"
        "CREATE TABLE public.customer_orders (\n"
        "  order_id varchar(40) PRIMARY KEY,\n"
        "  customer_name varchar(200) NOT NULL,\n"
        "  supplier_id varchar(80) NOT NULL,\n"
        "  sku varchar(80) NOT NULL,\n"
        "  quantity integer NOT NULL CHECK (quantity > 0),\n"
        "  promised_date date NOT NULL,\n"
        "  penalty_per_day_gbp numeric(14, 2) NOT NULL CHECK (penalty_per_day_gbp >= 0)\n"
        ");\n"
        "INSERT INTO public.customer_orders\n"
        "  (order_id, customer_name, supplier_id, sku, quantity, promised_date, penalty_per_day_gbp)\n"
        f"VALUES\n{values};\n"
    )
    return {"postgres_orders.sql": orders, "suppliers.csv": suppliers, "inventory.csv": inventory}


def main(argv: list[str]) -> int:
    files = render(FixtureRepository().snapshot())
    if "--check" in argv:
        stale = [name for name, text in files.items()
                 if not (OUT_DIR / name).exists() or (OUT_DIR / name).read_text(encoding="utf-8") != text]
        print("stale: " + ", ".join(stale) if stale else "zetaris_dataset is up to date")
        return 1 if stale else 0
    OUT_DIR.mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT_DIR / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
